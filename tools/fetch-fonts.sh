#!/bin/sh
# Download the site's fonts (Latin subset, woff2) so the page works offline,
# and write css/fonts.css with matching @font-face rules.
# Run from the repository root:  sh tools/fetch-fonts.sh
set -eu
cd "$(dirname "$0")/.."
UA="Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"
URL="https://fonts.googleapis.com/css2?family=Caveat:wght@400;600&family=Atkinson+Hyperlegible:ital,wght@0,400;0,700;1,400;1,700&family=Jost:wght@500;600;700;800&display=swap"
mkdir -p fonts
tmp=$(mktemp)
curl -fsS -A "$UA" "$URL" -o "$tmp"
out=css/fonts.css
echo "/* Self-hosted fonts (Latin subset), generated by tools/fetch-fonts.sh from Google Fonts. */" > "$out"
# Google serves one block per subset; keep the "latin" blocks only.
awk '/^\/\* latin \*\//{keep=1; next} /^\/\* /{keep=0} keep' "$tmp" > "$tmp.latin"
# Each block: family, style, weight, src url. Variable fonts (Jost, Caveat) come back as one
# file shared by several weights, so faces with the same file collapse into one weight range.
awk 'BEGIN{RS="}"} /@font-face/{
  fam=$0; sub(/.*font-family: \x27/, "", fam); sub(/\x27.*/, "", fam)
  sty=$0; sub(/.*font-style: /, "", sty); sub(/;.*/, "", sty)
  wt=$0;  sub(/.*font-weight: /, "", wt);  sub(/;.*/, "", wt)
  src=$0; sub(/.*src: url\(/, "", src); sub(/\).*/, "", src)
  k=fam "|" sty "|" src
  if (!(k in lo)) { order[++n]=k; lo[k]=wt; hi[k]=wt }
  if (wt+0 < lo[k]+0) lo[k]=wt
  if (wt+0 > hi[k]+0) hi[k]=wt
} END { for (i=1; i<=n; i++) { k=order[i]; split(k, f, "|"); print f[1] "|" f[2] "|" lo[k] "|" hi[k] "|" f[3] } }' "$tmp.latin" |
while IFS='|' read -r fam sty lo hi src; do
  suffix=""
  if [ "$sty" = italic ]; then suffix=i; fi
  if [ "$lo" = "$hi" ]; then weight=$lo; file="fonts/$(echo "$fam" | tr -d ' ')-$lo$suffix.woff2"
  else weight="$lo $hi"; file="fonts/$(echo "$fam" | tr -d ' ')$suffix.woff2"; fi
  curl -fsS -A "$UA" "$src" -o "$file"
  printf "@font-face { font-family: '%s'; font-style: %s; font-weight: %s; font-display: swap; src: url(../%s) format('woff2'); }\n" "$fam" "$sty" "$weight" "$file" >> "$out"
  echo "saved $file"
done
rm -f "$tmp" "$tmp.latin"
echo "wrote $out"
